void LibBgfxBackend::merge_material_groups(ScxGeometry& geo) {
  if (geo.groups.size() < 2) return;
  const bool v3 = geo.info.version == 3, v4 = geo.info.version == 4;
  for (const auto& group : geo.groups) {
    // Blended sections are drawn in their stored order. Leave such a mesh as is.
    if ((v4 && (group.material_flags & 0x40000000u)) ||
        (v3 && (group.material_flags & 0x101u) == 0x101u))
      return;
    if (static_cast<size_t>(group.index_start) + group.index_count > geo.indices.size()) return;
  }
  // Materials in order of first use; each keeps its sections in stored order.
  std::vector<size_t> material_of(geo.groups.size());
  std::vector<size_t> first;
  for (size_t i = 0; i < geo.groups.size(); ++i) {
    size_t m = 0;
    while (m < first.size() && !same_material(geo.groups[first[m]], geo.groups[i])) ++m;
    if (m == first.size()) first.push_back(i);
    material_of[i] = m;
  }
  if (first.size() == geo.groups.size()) return;
  std::vector<uint32_t> indices;
  indices.reserve(geo.indices.size());
  std::vector<ScxGroup> groups;
  groups.reserve(first.size());
  for (size_t m = 0; m < first.size(); ++m) {
    ScxGroup merged = geo.groups[first[m]];
    merged.index_start = static_cast<uint32_t>(indices.size());
    for (size_t i = 0; i < geo.groups.size(); ++i) {
      if (material_of[i] != m) continue;
      const auto begin = geo.indices.begin() + geo.groups[i].index_start;
      indices.insert(indices.end(), begin, begin + geo.groups[i].index_count);
    }
    merged.index_count = static_cast<uint32_t>(indices.size()) - merged.index_start;
    groups.push_back(std::move(merged));
  }
  geo.indices = std::move(indices);
  geo.groups = std::move(groups);
  geo.info.groups = static_cast<int32_t>(geo.groups.size());
}

SceneFrustum LibBgfxBackend::view_frustum(const float* view, const float* projection) {
    float clip[16];
    bx::mtxMul(clip, view, projection);
    SceneFrustum frustum;
    for (size_t i = 0; i < frustum.size(); ++i) {
      const size_t axis = i / 2;
      const float sign = i % 2 ? -1.f : 1.f;
      auto& plane = frustum[i];
      for (size_t component = 0; component < 4; ++component) {
        const size_t offset = component * 4;
        plane[component] = i == 4 && !bgfx::getCaps()->homogeneousDepth
            ? clip[offset + 2] : clip[offset + 3] + sign * clip[offset + axis];
      }
      const float normal = std::hypot(plane[0], plane[1], plane[2]);
      if (normal > 0.f)
        for (auto& component : plane) component /= normal;
    }
    return frustum;
}

  void LibBgfxBackend::sync_instances(const float* view, const float* projection)
{
    float camera[16];
    bx::mtxInverse(camera, view);
    const float eye[3] = {camera[12], camera[13], -camera[14]};
    std::memcpy(hiz_eye_, eye, sizeof(hiz_eye_));
    std::memcpy(cull_view_, view, sizeof(cull_view_));
    std::memcpy(cull_proj_, projection, sizeof(cull_proj_));
    scene_instances_set_hiz(&LibBgfxBackend::hiz_keep, this);
    const auto frustum = view_frustum(view, projection);
    std::vector<std::shared_ptr<const ScxGeometry>> resident_props;
    {
      // Diagnostic: the right-hand body parts of some cars reflect wrongly
      // from the start. A mirrored part (negative determinant) flips the
      // winding, and if the normal transform does not account for it the
      // normals point inward. Log the determinant and the scale signs.
      static int logged = 0;
      if (logged < 24) {
        for (const auto& i : instances_) {
          const float* m = i.transform.data();
          const float det = m[0]*(m[5]*m[10]-m[6]*m[9]) - m[1]*(m[4]*m[10]-m[6]*m[8]) + m[2]*(m[4]*m[9]-m[5]*m[8]);
          if (std::fabs(det) < 1e-8f) continue;
          std::fprintf(stderr,
              "[refl] part det=%+.4f pos=%+.2f %+.2f %+.2f ver=%u "
              "paint_slot=%d veh=%d tex='%s'\n",
              det, m[12], m[13], m[14],
              unsigned(i.geometry ? i.geometry->info.version : 0u),
              i.paint_slot, i.vehicle_material ? 1 : 0, i.paint_texture.c_str());
          if (++logged >= 24) break;
        }
      }
    }
    instances_ = scene_instances_collect(&frustum, &resident_props);
    prop_batches_.clear();
    scene_instances_collect_batches(&frustum, prop_batches_);
    scene_instances_set_hiz(nullptr, nullptr);
    previews_.clear();
    for(const auto* camera:gameref_active_cameras()) {
      const auto* vp=gameref_get(camera->viewport);
      if(!vp||!vp->vp_active||vp->vp_w<=0||vp->vp_h<=0||(vp->vp_w>=.99f&&vp->vp_h>=.99f))continue;
      void* root=camera->parent;
      auto objects=scene_instances_collect_root(root);
      if(objects.empty()&&camera->aim_look) {
        if(auto* look=gameref_find_live(camera->look_id))
          objects=scene_instances_collect_root(look->key);
      }
      if(!objects.empty())previews_.push_back({*camera,*vp,std::move(objects),true});
    }
    std::sort(previews_.begin(),previews_.end(),[](const Preview&a,const Preview&b){return a.viewport.vp_pri!=b.viewport.vp_pri?a.viewport.vp_pri<b.viewport.vp_pri:a.viewport.vp_x<b.viewport.vp_x;});
    std::unordered_map<const ScxGeometry*,bool> used;
    std::unordered_map<void*, const ScxGeometry*> current_deformed;
    auto cache = [&](const std::shared_ptr<const ScxGeometry>& source, void* owner,
                     bool map_prop = false) {
      const auto* key = source.get();
      used[key] = true;
      const auto* node = owner ? gameref_get(owner) : nullptr;
      const bool deformed = node && node->deformed_geometry.get() == key;
      if (deformed) current_deformed[owner] = key;
      if (auto found = instance_meshes_.find(key); found != instance_meshes_.end()) {
        ScenePart& part = found->second;
        if (part.revision != source->revision) {
          if (bgfx::isValid(part.vbh)) bgfx::destroy(part.vbh);
          if (bgfx::isValid(part.skin_vbh)) bgfx::destroy(part.skin_vbh);
          if (bgfx::isValid(part.ibh)) bgfx::destroy(part.ibh);
          part.vbh = BGFX_INVALID_HANDLE;
          part.skin_vbh = BGFX_INVALID_HANDLE;
          part.ibh = BGFX_INVALID_HANDLE;
          part.geo.positions = source->positions;
          part.geo.normals = source->normals;
          part.revision = source->revision;
          part.upload_bytes = part.geo.positions.size() * sizeof(MeshVertex) +
                              part.geo.indices.size() * sizeof(uint32_t);
          part.pending = true;
          pending_uploads_.push_back(key);
        }
        return;
      }
      ScenePart part;
      part.source = source;
      part.geo = *source;
      // Static map meshes repeat a few materials across hundreds of sections.
      // Keep one draw per material instead of one per section.
      if (!deformed && (map_prop || source->ground_polygons)) merge_material_groups(part.geo);
      part.share_textures = map_prop;
      part.upload_bytes = part.geo.positions.size() * sizeof(MeshVertex) +
                          part.geo.indices.size() * sizeof(uint32_t);
      part.revision = source->revision;
      if (deformed) {
        const auto previous = deformed_meshes_.find(owner);
        if (previous != deformed_meshes_.end()) {
          auto old = instance_meshes_.find(previous->second);
          if (old != instance_meshes_.end() && old->second.geo.textures == part.geo.textures &&
              old->second.geo.info.path == part.geo.info.path) {
            // Reuse the previous handles: no texture upload needed.
            part.tex = std::move(old->second.tex);
            part.shared_texture_paths = std::move(old->second.shared_texture_paths);
          }
        }
      }
      // Defer the GPU upload into flush_pending_uploads() so a streaming
      // burst cannot stall a single frame (PERF-1). The draw path skips
      // parts without valid buffers until their turn comes.
      part.pending = true;
      pending_uploads_.push_back(key);
      instance_meshes_.emplace(key, std::move(part));
    };
    // Resident map models are shared by their placements. Camera culling only
    // affects draw submission; leaving the map releases the GPU resources.
    for (const auto& mesh : resident_props) cache(mesh, nullptr, true);
    for (const auto& instance : instances_)
      if (!instance.sky) cache(instance.geometry, instance.key);
    for (const auto& preview : previews_)
      for (const auto& instance : preview.instances) cache(instance.geometry, instance.key);
    // Frame-budgeted uploads first: parts flushed here become drawable and
    // their skins can upload in the same pass.
    flush_pending_uploads();
    auto ensure_skin = [&](const SceneInstance& instance) {
      if (!instance.gpu_skin || !instance.geometry) return;
      auto found = instance_meshes_.find(instance.geometry.get());
      if (found == instance_meshes_.end() || bgfx::isValid(found->second.skin_vbh)) return;
      upload_skin(found->second);
    };
    for (const auto& instance : instances_) ensure_skin(instance);
    for (const auto& preview : previews_)
      for (const auto& instance : preview.instances) ensure_skin(instance);
    for(auto it=instance_meshes_.begin();it!=instance_meshes_.end();) {
      if(used.count(it->first)){++it;continue;}destroy_part(it->second);it=instance_meshes_.erase(it);
    }
    deformed_meshes_ = std::move(current_deformed);
  }
  void LibBgfxBackend::flush_pending_uploads()
{
    // Spread new geometry/texture uploads across frames (PERF-1). Entering a
    // new district used to build vertex buffers and decode a batch of DDS
    // files inside one frame; the frame queue backed up and every present
    // stalled while the GPU sat idle. Limits are generous: ~8 MB of geometry
    // and 6 texture files per frame sustain far more than any streaming
    // demand, while capping the worst frame at a couple of milliseconds.
    constexpr size_t kBudgetBytes = 8u << 20;
    constexpr int kBudgetTextures = 6;
    size_t bytes = kBudgetBytes;
    int textures = kBudgetTextures;
    for (auto it = pending_uploads_.begin(); it != pending_uploads_.end();) {
      auto found = instance_meshes_.find(*it);
      if (found == instance_meshes_.end() || !found->second.pending) {
        it = pending_uploads_.erase(it);
        continue;
      }
      ScenePart& part = found->second;
      if (bytes == 0) {
        ++it;
        continue;
      }
      bytes = part.upload_bytes >= bytes ? 0 : bytes - part.upload_bytes;
      upload_part(part);
      if (part.tex.empty())
        textures -= load_part_textures(part, part.share_textures);
      part.pending = false;
      it = pending_uploads_.erase(it);
      if (textures <= 0) break;
    }
  }
void LibBgfxBackend::update_local_light() {
    local_light_ = {};
    if (!garage_ || !host_enhanced_graphics().local_lights) return;
    for (const auto* node : gameref_directional_lights()) {
      float matrix[16];
      if ((node->type_id & 0xffff) != 0x001d ||
          !scene_instances_script_matrix(node->key, matrix)) continue;
      // Stock garage scripts put the neon light at the map origin.
      // Position the emitter above the bay, at approximate fixture height.
      local_light_ = {matrix[12], matrix[13] + 3.3f, -matrix[14], 8.f};
      break;
    }
}

