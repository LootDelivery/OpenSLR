; ===========================================================================
; SLRR Native Fonts - полный исходник хука (иконки кузова + антикрэш)
; ===========================================================================
;
; Это ЧЕЛОВЕКО-ЧИТАЕМЫЙ исходник того же машинного кода, который генерирует
; slrr_font_hook.py. Держится для тех, кто хочет ПОНЯТЬ хук, изменить его
; (например, другой класс глифов / другой профиль TTF) и собрать руками.
;
; Сборка (NASM, https://www.nasm.us):
;     nasm -f bin hook_source.asm -o hook.bin
; hook.bin кладётся в exe по адресу CAVE1_VA (см. ниже), после чего
; правятся три точки входа - все они перечислены внизу файла.
;
; Все адреса ниже - от эталонной сборки native fonts v4.1 gate
; (ImageBase 0x400000). В СВОЕЙ сборке возьмите адреса из отчёта патчера
; (<exe>.HookReport.txt): классификатор, fallback, таблица, пещеры.
; Меняете адреса -> пересобираете -> хук работает на вашей сборке.

; ---------------------------------------------------------------------------
; КОНФИГ - подставьте СВОИ адреса из HookReport.txt
; ---------------------------------------------------------------------------
CAVE1_VA    equ 0x7F2C10        ; адрес пещеры 1 (свободное место в секции кода мода)
CAVE2_VA    equ 0x7F2C10+0x60   ; адрес пещеры 2 (cave1 + 0x60)
FALLBACK_VA equ 0x7F2807        ; fallback-классификатор мода (цена range-fail ja)
TABLE_VA    equ 0x7F0CD0        ; таблица маршрутизации шрифтов (16 записей по 0x38)
ENTRIES     equ 16              ; число записей таблицы (в моде: mov edi,0x20 / add edi,-2)

CLASS_STOCK equ 0               ; класс глифов "не текст" (иконки схемы кузова)
OUT_SLOT    equ 3               ; out[0] для px=15 (как в оригинальном моде)
OUT_PROFILE equ 8               ; out[4] для px=15 (TTF-профиль, как в оригинале)

org CAVE1_VA

; ---------------------------------------------------------------------------
; ПЕЩЕРА 1 - вход из range-fail (ja), ДО push'ей классификатора
; ---------------------------------------------------------------------------
; Соглашение о вызове классификатора: __cdecl, (descriptor, out).
; Стек при входе сюда: [esp]=ret, [esp+4]=descriptor, [esp+8]=out.
; Логика: ищем descriptor в таблице маршрутизации; если запись найдена и её
; класс глифов (entry+8) равен 0 - это ИКОНКИ (схема кузова и пр.), отдаём
; их штатному рендеру игры (return 0). Иначе - ведём себя как оригинальный
; мод (jmp fallback: descriptor+0x20 != 0 -> TTF-профиль {3,8}).
; ---------------------------------------------------------------------------
cave1:
        push    edi
        push    esi
        mov     ecx, [esp+0xC]          ; ecx = descriptor
        mov     edx, TABLE_VA           ; edx = таблица маршрутизации
        mov     esi, ENTRIES            ; esi = счётчик записей
.scan1: cmp     dword [edx-0x10], 0     ; запись активна?  (entry+0xC)
        je      .n1
        cmp     [edx-0x1C], ecx         ; это наш descriptor? (entry+0)
        je      .found_a
.n1:    cmp     dword [edx+0xC], 0      ; вторая половина активна? (entry+0x28)
        je      .adv1
        cmp     [edx], ecx              ; второй descriptor?  (entry+0x1C)
        je      .found_b
.adv1:  add     edx, 0x38               ; следующая запись (stride 0x38)
        dec     esi
        jnz     .scan1
        pop     esi                     ; не найдена -> оригинальное поведение мода
        pop     edi
        jmp     FALLBACK_VA
.found_a:
        sub     edx, 0x1C               ; edx -> начало записи
.found_b:
        mov     ecx, [edx+8]            ; ecx = class (entry+8)
        pop     esi
        pop     edi
        test    ecx, ecx
        jz      .stock                  ; класс 0 -> иконки: стоковый рендер
        jmp     FALLBACK_VA             ; класс 1/2 -> оригинальный fallback (TTF)
.stock:
        xor     eax, eax                ; return 0  (сток)
        ret

; ---------------------------------------------------------------------------
; ПЕЩЕРА 2 - вход из кейса px=15 (jump-таблица), ПОСЛЕ push'ей классификатора
; ---------------------------------------------------------------------------
; Стек при входе: [esp+0xC]=descriptor, [esp+0x10]=out (esp уже со сдвигом
; на push edi/push esi самого классификатора).
; Отличие от оригинального кейса: перед выдачей TTF-профиля проверяем класс
; глифов. Класс 0 -> сток; класс!=0 -> ЗАПИСЫВАЕМ out={SLOT,PROFILE} тем же
; способом, что и оригинальный эпилог классификатора (mov eax,[esp+0x10];
; mov [eax],esi; mov [eax+4],edi) - детерминированно, без опоры на мусор
; в стеке вызывающего кода.
; ---------------------------------------------------------------------------
times CAVE2_VA-CAVE1_VA-($-$$) db 0    ; добивка до CAVE2_VA

cave2:
        mov     ecx, [esp+0xC]          ; ecx = descriptor
        mov     edx, TABLE_VA
        mov     esi, ENTRIES
.scan2: cmp     dword [edx-0x10], 0
        je      .n2
        cmp     [edx-0x1C], ecx
        je      .found_a
.n2:    cmp     dword [edx+0xC], 0
        je      .adv2
        cmp     [edx], ecx
        je      .found_b
.adv2:  add     edx, 0x38
        dec     esi
        jnz     .scan2
        jmp     .ttf                    ; не найдена -> как оригинал: TTF
.found_a:
        sub     edx, 0x1C
.found_b:
        mov     ecx, [edx+8]            ; class
        test    ecx, ecx
        jz      .stock
.ttf:   mov     esi, OUT_SLOT           ; out[0] = слот
        mov     edi, OUT_PROFILE        ; out[4] = TTF-профиль
        mov     eax, [esp+0x10]         ; eax = out
        mov     [eax], esi
        mov     [eax+4], edi
        mov     eax, 1                  ; return 1 (TTF-путь)
        pop     esi                     ; снимаем push'и КЛАССИФИКАТОРА
        pop     edi
        ret
.stock:
        pop     esi
        pop     edi
        xor     eax, eax                ; return 0  (сток)
        ret

; ===========================================================================
; ТРИ ТОЧКИ ВХОДА (правки в существующем коде мода)
; ===========================================================================
; Их нельзя "собрать" отдельным файлом - это правки готового кода.
; Патчер делает их автоматически; вручную - в HxD/xvi32 по сигнатурам.
;
; [A] SITE-A: range-fail переход классификатора (6 байт, на месте)
;     где:   сигнатура "31 C0 83 C1 F9 83 F9 26 0F 87 xx xx xx xx 57 56 ..."
;           0F 87 rel32 - это ja <fallback>; rel32 = адрес fallback.
;     было:  0F 87 <rel32 -> FALLBACK_VA>      (ja fallback)
;     стало: 0F 87 <rel32 -> CAVE1_VA>         (ja cave1)
;     rel32 = target - (адрес_этой_инструкции + 6), little-endian.
;
; [B] SITE-B: кейс px=15 в jump-таблице классификатора (12 байт, на месте)
;     где:   сигнатура "BF 08 00 00 00 BE 03 00 00 00 EB xx"
;           (mov edi,8; mov esi,3; jmp <эпилог>) - сразу за кейсом px=20
;           (mov esi,2; jmp), перед кейсом px=20' (mov edi,6).
;     было:  BF 08 00 00 00 BE 03 00 00 00 EB 6E
;     стало: E9 <rel32 -> CAVE2_VA> 90 90 90 90 90 90 90
;     rel32 = CAVE2_VA - (адрес_E9 + 5), little-endian.
;
; [C] ANTI-CRASH: стаб в fallback-классификаторе (3 байта, на месте)
;     где:  тело fallback: "8B 4C 24 04 83 79 20 00 74 xx ..." -
;           байт xx (disp8 у je) указывает crash-сайт: je_addr+2+xx.
;     было: 00 00 00                  (нули - je вёл в нули = краш)
;     стало: 31 C0 C3                 (xor eax,eax; ret -> return 0 = сток)
;
; [D] VirtualSize секции с кодом мода (если пещеры за пределами VirtualSize):
;     поле VirtualSize в заголовке секции (смещение +8 в entry секции) ->
;     увеличить до SizeOfRawData. Патчер делает сам и проверяет SizeOfImage.
;
; [E] Пересчитать PE-контрольную сумму (offset OptionalHeader+64).
;     Патчер делает сам (алгоритм из спецификации PE).
; ===========================================================================
